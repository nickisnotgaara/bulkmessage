"""Планировщик личного окна: случайные моменты отправок, размазанные по нему.

Зачем
----
Владелец 2026-10-09: если личные каналы (Telegram/MAX) отправляют в лимит, то
отправки должны идти в случайные моменты за оставшееся время, а не все за
минуту. Иначе 50 сообщений подряд — это сигнал бота, и цена ему — бан личного
номера владельца.

Почему нельзя просто «разделить окно на N»
-----------------------------------------
Равномерный шаг ``окно / N`` даёт одинаковые интервалы между отправками — а
именно одинаковые интервалы и выглядят как робот. Поэтому берём случайные веса
и нормируем их так, чтобы сумма сошла к длине окна: интервалы получаются
разными, а бюджет времени остаётся тем же.

Пример для 70 отправок в окне 11 часов: средний интервал ~9.4 минуты, но
конкретные паузы скачут от ~5 до ~14 минут.

Почему это отдельный модуль
---------------------------
Тут нет ни БД, ни сети, ни config — только математика времени. Именно поэтому
её можно проверить тестами без стенда: за утверждением «отправки размазаны по
окну» должно стоять проверяемое утверждение, а не доверие к коду.
"""

from __future__ import annotations

import random
from typing import Optional

# Насколько интервал может отличаться от среднего. 0.5–1.5 — разница втрое,
# чего достаточно, чтобы убрать машинную регулярность, и мало, чтобы никто не
# ждал сутки между двумя сообщениями.
MIN_WEIGHT = 0.5
MAX_WEIGHT = 1.5

# Разброс СВЕРХ минимума по умолчанию. Значение 1.0 здесь было бы ловушкой:
# множители uniform(1.0, 1.0) дают ровный шаг — ровно то «поведение бота»,
# ради устранения которого параметр и добавлен. Поэтому дефолт совпадает с
# config.PERSONAL_JITTER_MAX, и забытый аргумент не отключает разброс молча.
DEFAULT_JITTER_MAX = 1.4


def build_slot_schedule(
    n_slots: int,
    window_seconds: float,
    *,
    rng: Optional[random.Random] = None,
    min_gap_seconds: float = 0.0,
    jitter_max: float = DEFAULT_JITTER_MAX,
) -> list[float]:
    """Моменты отправок в секундах от начала окна, строго возрастающие.

    Гарантии, на которые опирается sender:

    * ровно ``n_slots`` значений;
    * строго возрастают (две отправки не могут выпасть на одну секунду);
    * первый ≥ 0, последний ≤ ``window_seconds`` — отправка никогда не
      выпадает за пределы окна;
    * сумма интервалов равна длине окна с точностью до округления.

    ``min_gap_seconds`` — ЖЁСТКИЙ минимум между соседними отправками
    (решение владельца 2026-10-10: не меньше 15 минут между сообщениями
    в личных каналах). Без этого параметра разброс 0.5–1.5× от среднего
    давал интервалы КОРОЧЕ минимума, и запрет не выполнялся.

    ``jitter_max`` — во сколько раз максимум интервал может превысить
    минимум. Нужен потому, что ровный шаг в 15 минут для личного аккаунта
    ХУЖЕ случайного: это сигнал бота. Поэтому слотов в окно влезает
    меньше, чем window // min_gap, — за счёт запаса под разброс.

    Пустое окно или ноль слотов даёт пустой список, а не исключение: окно
    может закрыться до того, как фаза успела начаться.
    """
    if n_slots <= 0 or window_seconds <= 0:
        return []

    _min = max(0, int(min_gap_seconds))
    if _min <= 0:
        # Старый режим: сумма интервалов равна длине окна.
        weights = [
            (rng or random).uniform(MIN_WEIGHT, MAX_WEIGHT)
            for _ in range(n_slots)
        ]
        total = sum(weights)
        gaps = [w / total * window_seconds for w in weights]
    else:
        # Режим с минимумом: каждый интервал = минимум × случайный множитель.
        # Множитель НИЖЕ единицы не встречается — значит интервал не может
        # стать короче минимума ни при каком рандоме.
        _j = max(1.0, float(jitter_max or 1.0))
        _r = rng or random
        # Подбираем число слотов так, чтобы даже «дорогой» набор уложился.
        _mults = [_r.uniform(1.0, _j) for _ in range(n_slots)]
        while n_slots > 1 and _min * sum(_mults) > window_seconds:
            n_slots -= 1
            _mults = _mults[:n_slots]
        if _min * sum(_mults) > window_seconds:
            return []
        gaps = [_min * m for m in _mults]

    # Округление до целых секунд накапливает ошибку до нескольких секунд на
    # длинном расписании. Разницу отдаём первому интервалу: сумма после
    # этого совпадает с окном, а порядок остаётся строго возрастающим.
    #
    # В режиме с минимумом отрицательную коррекцию отбрасываем: иначе
    # округление вниз уронило бы первый интервал ниже гарантированного
    # минимума, и запрет «не меньше N минут» перестал бы выполняться.
    rounded = [int(g) for g in gaps]
    drift = int(round(window_seconds)) - sum(rounded)
    if _min <= 0:
        if rounded:
            rounded[0] += drift
    elif drift > 0 and rounded:
        rounded[0] += drift
    else:
        for _i, _g in enumerate(rounded):
            if _g < _min:
                rounded[_i] = _min

    slots: list[float] = []
    cursor = 0.0
    for gap in rounded:
        if gap <= 0:
            # Вырожденный интервал (окно меньше числа слотов) — сдвигаем на
            # секунду, иначе моменты схлопнутся и порядок перестанет быть
            # строго возрастающим.
            gap = 1
        cursor += gap
        slots.append(cursor)
    return slots


def describe(slots: list[float]) -> str:
    """Человекочитаемая сводка расписания — попадает в лог перед прогоном."""
    if not slots:
        return "расписание пустое"
    gaps = [round(b - a) for a, b in zip(slots, slots[1:])]
    if not gaps:
        return (f"{len(slots)} слотов, единственный интервал "
                f"{round(slots[0])} с")
    return (
        f"{len(slots)} слотов, первый через {round(slots[0])} с, "
        f"последний через {round(slots[-1])} с; "
        f"интервалы мин {min(gaps)} / медиана "
        f"{sorted(gaps)[len(gaps) // 2]} / макс {max(gaps)} с"
    )